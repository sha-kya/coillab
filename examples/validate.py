"""Validate CoilLab's inductance models against independent public references.

Writes ``docs/validation.md`` (a table) and ``docs/validation.png`` (a chart).
Run from the repository root:  python examples/validate.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from coillab import CircularCoil, PCBSquareSpiral, SquareCoil, eng
from coillab import inductance as ind
from coillab import references as ref
from coillab.constants import MU0

DOCS = Path(__file__).resolve().parents[1] / "docs"


def cases():
    out = []

    m = ind.mutual_coaxial_loops(0.10, 0.12, 0.03)
    n = ref.neumann_mutual(ref.circle_path(0.10, 0, 3000), ref.circle_path(0.12, 0.03, 3000))
    out.append(("Two coaxial loops (M)", "Brute-force Neumann integral", m, n))

    for side, a in [(0.1, 0.5e-3), (1.0, 0.25e-3)]:
        c = SquareCoil(side=side, n_turns=1, wire_diameter=2 * a)
        out.append((f"Square loop, {side * 1e3:.0f} mm", "Grover", c.inductance(), ref.grover_square_loop(side, a)))

    for radius, n_t, wire in [(0.02, 100, 0.5e-3), (0.05, 60, 1e-3)]:
        c = CircularCoil(radius=radius, n_turns=n_t, wire_diameter=wire)
        out.append((f"Solenoid, r={radius * 1e3:.0f} mm, N={n_t}", "Wheeler single-layer",
                    c.inductance(), ref.wheeler_single_layer(radius, n_t * c.pitch, n_t)))

    p = 1.04e-3
    c = CircularCoil(radius=0.03 - 8 * p, n_turns=323, wire_diameter=1e-3, turns_per_layer=19)
    out.append(("Multilayer, N=323", "Wheeler multilayer", c.inductance(),
                ref.wheeler_multilayer(0.03, 19 * c.pitch, 17 * c.pitch, 323)))

    c = CircularCoil(radius=0.15, n_turns=80, wire_diameter=0.5e-3, turns_per_layer=10)
    q = c.pitch
    r_mean = 0.15 + 3.5 * q
    gmd_l = MU0 * 80**2 * r_mean * (np.log(8 * r_mean / (0.2235 * 18 * q)) - 2)
    out.append(("Thin bundle, r=150 mm, N=80", "Maxwell ring with GMD", c.inductance(), gmd_l))

    for d_out, n_t, w, s in [(0.1, 20, 0.3e-3, 0.3e-3), (0.05, 10, 0.5e-3, 0.25e-3), (0.2, 30, 1e-3, 0.5e-3)]:
        c = PCBSquareSpiral(outer_side=d_out, turns_per_layer=n_t, trace_width=w, spacing=s)
        out.append((f"PCB spiral, {d_out * 1e3:.0f} mm, N={n_t}", "Mohan et al. current sheet",
                    c.inductance(), ref.mohan_current_sheet(n_t, d_out, c.inner_side)))
    return out


def write_table(rows) -> str:
    lines = ["| Case | Reference | CoilLab | Reference value | Difference |",
             "| --- | --- | --- | --- | --- |"]
    for name, src, ours, theirs in rows:
        lines.append(f"| {name} | {src} | {eng(ours, 'H')} | {eng(theirs, 'H')} | {100 * (ours / theirs - 1):+.2f}% |")
    return "\n".join(lines)


def plot(rows, path: Path) -> None:
    import matplotlib.pyplot as plt

    ink, quiet, grid, blue = "#0b0b0b", "#52514e", "#e4e3df", "#2a78d6"
    names = [r[0] for r in rows][::-1]
    errs = [100 * (r[2] / r[3] - 1) for r in rows][::-1]
    fig, ax = plt.subplots(figsize=(7.5, 0.42 * len(rows) + 1.3), dpi=150)
    fig.patch.set_facecolor("#fcfcfb")
    ax.set_facecolor("#fcfcfb")
    ax.axvspan(-2, 2, color="#cde2fb", alpha=0.6, lw=0)
    ax.axvline(0, color=quiet, lw=1)
    y = np.arange(len(names))
    ax.hlines(y, 0, errs, color=blue, lw=2)
    ax.plot(errs, y, "o", color=blue, ms=7, mec="#fcfcfb", mew=2)
    for yi, e in zip(y, errs):
        ax.text(e + (0.15 if e >= 0 else -0.15), yi, f"{e:+.2f}%", va="center",
                ha="left" if e >= 0 else "right", fontsize=8.5, color=quiet)
    ax.set_yticks(y, names, fontsize=9, color=ink)
    ax.set_xlim(-3.5, 3.5)
    ax.set_xlabel("CoilLab vs reference (%)", color=quiet, fontsize=9)
    ax.tick_params(colors=quiet, length=0)
    ax.grid(axis="x", color=grid, lw=0.8)
    ax.set_axisbelow(True)
    for spine in ax.spines.values():
        spine.set_visible(False)
    ax.set_title("Every inductance check lands within ±2% of its reference (shaded)", loc="left",
                 fontsize=11, color=ink, fontweight="bold", pad=12)
    fig.tight_layout()
    fig.savefig(path, facecolor=fig.get_facecolor())


def main() -> None:
    rows = cases()
    DOCS.mkdir(exist_ok=True)
    table = write_table(rows)
    (DOCS / "validation.md").write_text(
        "# Validation\n\nGenerated by `examples/validate.py`. Each row compares CoilLab's inductance model "
        "with an independent method from the public literature.\n\n" + table + "\n\n![validation](validation.png)\n"
    )
    print(table)
    try:
        plot(rows, DOCS / "validation.png")
    except ImportError:
        print("matplotlib not installed; skipped the chart (pip install coillab[plot])")


if __name__ == "__main__":
    main()
